def main(catalog_js, out_dir):
    txt = open(catalog_js, encoding='utf-8').read()
    cat = json.loads(txt[txt.index('{'):txt.rindex('}') + 1])
    docs = {d['id']: d for d in cat['docs']}

    def nm(d):
        return re.sub(r'\.(pdf|zip)$', '', d['name'])

    def year(d):
        return d['year'] if d['year'] and d['year'] != '미표기' else '발행연도 미표기'

    def expand(s):
        def rep(m):
            d = docs.get(m.group(1))
            return f"「{nm(d)}」({year(d)})" if d else m.group(0)
        return re.sub(r'\b(D\d{2})\b', rep, s)

    def check_ref(r):
        return expand(r)

    os.makedirs(out_dir, exist_ok=True)
    index = []
    for k, c in CONTENT.items():
        title = cat['cats'][str(k)]
        members = [d for d in cat['docs'] if d['cat'] == k]
        lines = [f"# {c['icon']} {title}", "",
                 f"> 자료 기준일 {cat['asof']} · 이 카테고리 자료 {len(members)}건. 체크리스트의 [근거]는 원문 PDF 쪽(PDF 뷰어 기준)입니다.", "",
                 "## 1. 주요 관리 범위", ""]
        lines += [f"- {expand(s)}" for s in c['scope']]
        lines += ["", "## 2. 실무 담당자 핵심 체크리스트", ""]
        lines += [f"- [ ] {q}  \n  [근거] {check_ref(r)}" for q, r in c['check']]
        lines += ["", "## 3. 이 카테고리 자료", "", "| 연번 | 파일명 | 발행연도 | 발행기관 | 주요 대상 | 매체 |", "| --- | --- | --- | --- | --- | --- |"]
        for d in members:
            dup = ' (중복본)' if d.get('dupOf') else ''
            lines.append(f"| {d['id']} | {d['file']}{dup} | {year(d)} | {d['pub']} | {d['aud']} | {d['media']} |")
        lines += ["", "## 4. 초안 대비 검증 메모", ""]
        lines += [f"- {expand(s)}" for s in c['notes']]
        lines += ["", "이 문서는 첨부 자료에 근거한 일반 안내입니다. 자료와 현행 법령이 다르면 현행 법령(국가법령정보센터)을 따릅니다.", ""]
        folder = os.path.join(out_dir, title)
        os.makedirs(folder, exist_ok=True)
        open(os.path.join(folder, 'README.md'), 'w', encoding='utf-8').write('\n'.join(lines))
        index.append((title, len(members)))
    return index


if __name__ == '__main__':
    for t, n in main(sys.argv[1], sys.argv[2]):
        print(t, n)
